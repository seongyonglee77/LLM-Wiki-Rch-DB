    def test_symlink_outputs_are_refused_even_inside_project(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            db = self.make_db(base)
            project = base / "project"
            project.mkdir()
            outside = base / "outside"
            outside.mkdir()
            (project / "drafts").symlink_to(outside, target_is_directory=True)

            code, _out, err = self.run_main("--project", str(project), "--db-root", str(db), "--apply")
            self.assertEqual(code, 2)
            self.assertIn("existing symlink", err)

        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            db = self.make_db(base)
            project = base / "project"
            project.mkdir()
            real_status = project / "real-status.md"
            real_status.write_text("status\n", encoding="utf-8")
            (project / "STATUS.md").symlink_to(real_status)

            code, _out, err = self.run_main("--project", str(project), "--db-root", str(db), "--apply")
            self.assertEqual(code, 2)
            self.assertIn("existing symlink", err)

        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            db = self.make_db(base)
            project = base / "project"
            project.mkdir()
            (project / "STATUS.md").symlink_to(project / "missing-status.md")

            code, _out, err = self.run_main("--project", str(project), "--db-root", str(db), "--apply")
            self.assertEqual(code, 2)
            self.assertIn("existing symlink", err)


