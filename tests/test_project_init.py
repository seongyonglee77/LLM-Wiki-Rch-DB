    def test_malformed_or_mismatched_existing_config_refused(self):
        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            db = self.make_db(base)
            project = base / "project"
            project.mkdir()
            (project / "project-config.json").write_text("{bad json", encoding="utf-8")

            code, _out, err = self.run_main("--project", str(project), "--db-root", str(db), "--apply")
            self.assertEqual(code, 2)
            self.assertIn("Refusing malformed existing config", err)

        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            db = self.make_db(base)
            other_db = self.make_db(base, "other-db")
            project = base / "project"
            project.mkdir()
            (project / "project-config.json").write_text(
                json.dumps(
                    {
                        "schema_version": 1,
                        "db_root": str(other_db.resolve()),
                        "project_root": str(project.resolve()),
                        "search_paths": project_init.SEARCH_PATHS,
                    }
                ),
                encoding="utf-8",
            )

            code, _out, err = self.run_main("--project", str(project), "--db-root", str(db), "--apply")
            self.assertEqual(code, 2)
            self.assertIn("Existing config db_root differs", err)

        with tempfile.TemporaryDirectory() as tmp:
            base = Path(tmp)
            db = self.make_db(base)
            project = base / "project"
            project.mkdir()
            (project / "project-config.json").write_text(
                json.dumps(
                    {
                        "schema_version": 1,
                        "db_root": str(db.resolve()),
                        "project_root": str(project.resolve()),
                        "search_paths": project_init.SEARCH_PATHS,
                        "project_name": "old-extra-key",
                    }
                ),
                encoding="utf-8",
            )

            code, _out, err = self.run_main("--project", str(project), "--db-root", str(db), "--apply")
            self.assertEqual(code, 2)
            self.assertIn("unexpected keys", err)

